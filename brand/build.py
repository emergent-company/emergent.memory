def contrast_md() -> str:
    rows = ["| Pair | Ratio | Required | WCAG 2.2 |", "|---|---|---|---|"]
    failures = []
    for mode in ("dark", "light"):
        rows.append(f"| **{mode}** | | | |")
        for fg, bg, minimum, why in CONTRAST_PAIRS:
            f = COLOR[fg.replace("{mode}", mode)]
            b = COLOR[bg.replace("{mode}", mode)]
            ratio = contrast(f.linear, b.linear)
            ok = ratio >= minimum
            if not ok:
                failures.append(f"{mode}: {fg.replace('{mode}', mode)} on {bg.replace('{mode}', mode)} = {ratio:.2f} < {minimum} ({why})")
            rows.append(
                f"| `{fg.replace('semantic.{mode}.', '')}` on `{bg.replace('semantic.{mode}.', '')}` | {ratio:.2f} | {minimum} | {'pass' if ok else '**FAIL**'} |"
            )
    body = "\n".join(rows)
    return (
        f"<!-- {HEADER} -->\n\n"
        "# Contrast matrix\n\n"
        "Computed from the token file by `brand/build.py`. Text pairs target 4.5:1\n"
        "(WCAG 2.2 SC 1.4.3); UI-component pairs target 3:1 (SC 1.4.11).\n\n"
        f"{body}\n\n"
        + ("All pairs pass.\n" if not failures else "## Failures\n\n" + "\n".join(f"- {x}" for x in failures) + "\n")
    ), failures



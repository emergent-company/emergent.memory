def parse_glyph(art: str, name: str) -> tuple[set[tuple[int, int]], int, int]:
    """ASCII → cell set, asserting the lattice invariants."""
    rows = [r for r in art.strip("\n").split("\n")]
    if not rows:
        raise TokenError(f"{name}: empty glyph")
    width = len(rows[0])
    cells: set[tuple[int, int]] = set()
    for y, row in enumerate(rows):
        if len(row) != width:
            raise TokenError(f"{name}: row {y} is {len(row)} cells, expected {width}")
        for x, ch in enumerate(row):
            if ch == "#":
                cells.add((x, y))
            elif ch != ".":
                raise TokenError(f"{name}: unexpected {ch!r} at {x},{y}")
    if not cells:
        raise TokenError(f"{name}: no cells")

    stroke = SEM["logo.grid.stroke"]
    gap = SEM["logo.grid.gap"]
    if gap != stroke:
        raise TokenError("logo.grid.gap must equal logo.grid.stroke")
    # The invariant is thickness, not length: a segment may be 1-4u long along
    # its axis (that is a bar) but never thicker than 1u across it. On an
    # orthogonal lattice that is exactly "no filled 2x2 block anywhere", which
    # also rules out the fat shoulder that makes a stepped M look like a blob.
    for x, y in sorted(cells):
        if (x + 1, y) in cells and (x, y + 1) in cells and (x + 1, y + 1) in cells:
            raise TokenError(
                f"{name}: filled 2x2 block at {x},{y} — a segment may be long but never thicker than {stroke}u"
            )
    if len(rows) != int(SEM["logo.grid.capHeight"]):
        raise TokenError(f"{name}: {len(rows)} rows, cap-height is {SEM['logo.grid.capHeight']}u")
    if width < int(SEM["logo.grid.letterWidth"]):
        raise TokenError(f"{name}: {width}u wide, narrower than the {SEM['logo.grid.letterWidth']}u letter box")
    return cells, width, len(rows)


def to_rects(cells: set[tuple[int, int]]) -> list[tuple[int, int, int, int]]:
    """Merge cells into the fewest rectangles, so no seam lands inside the mark."""
    remaining = set(cells)
    rects: list[tuple[int, int, int, int]] = []
    for y in sorted({c[1] for c in cells}):
        x = 0
        max_x = max(c[0] for c in cells)
        while x <= max_x:
            if (x, y) not in remaining:
                x += 1
                continue
            x0 = x
            while (x, y) in remaining:
                x += 1
            x1 = x
            y1 = y + 1
            while all((xx, y1) in remaining for xx in range(x0, x1)):
                y1 += 1
            for yy in range(y, y1):
                for xx in range(x0, x1):
                    remaining.discard((xx, yy))
            rects.append((x0, y, x1 - x0, y1 - y))
    return rects


def mark_svg(art: str, name: str, unit: int = 24) -> str:
    """The mark alone on its 5x5 box, single colour via currentColor."""
    cells, w, h = parse_glyph(art, name)
    rects = to_rects(cells)
    body = "".join(
        f'<rect x="{x * unit}" y="{y * unit}" width="{rw * unit}" height="{rh * unit}"/>'
        for x, y, rw, rh in rects
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<!-- {HEADER.split(" — ")[0]} -->\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w * unit} {h * unit}" '
        'fill="currentColor" role="img" aria-label="Memory">\n'
        f"  {body}\n"
        "</svg>\n"
    )


def tile_svg(art: str, name: str, plate: Color, glyph: Color, unit: int = 24) -> str:
    """Self-contained tile: app icon, favicon, avatar, email.

    Explicit colours on purpose. `fill="currentColor"` only resolves when the
    SVG is inlined into the page (or used through a CSS mask); an <img>, a
    favicon or an email client has no CSS to inherit from and would paint the
    mark black on black. The plate and the glyph are both taken from the
    palette, so the tile cannot drift from the theme.
    """
    cells, w, h = parse_glyph(art, name)
    side = int(SEM["logo.tile.side"])
    px = side * unit
    ox = ((side - w) // 2) * unit
    oy = ((side - h) // 2) * unit
    body = "".join(
        f'<rect x="{ox + x * unit}" y="{oy + y * unit}" width="{rw * unit}" height="{rh * unit}" '
        f'fill="{glyph.hex}"/>'
        for x, y, rw, rh in to_rects(cells)
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f"<!-- {HEADER.split(' — ')[0]} -->\n"
        f'<!-- side = {side}u = 3 x cap-height; glyph centred, {SEM["logo.tile.pad"]}u of air each side -->\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {px} {px}" '
        'role="img" aria-label="Memory">\n'
        f'  <rect width="{px}" height="{px}" fill="{plate.hex}"/>\n'
        f"  {body}\n"
        "</svg>\n"
    )


def glyph_sheet_svg(unit: int = 24) -> str:
    """every sample letter on the same baseline, for the explore page."""
    parsed = {k: parse_glyph(v, k) for k, v in GLYPH_SAMPLES.items()}
    cap = int(SEM["logo.grid.capHeight"])
    pitch = int(SEM["logo.grid.pitch"])
    total_w = sum(w for _, w, _ in parsed.values()) * unit + pitch * unit * (len(parsed) - 1)
    total_h = cap * unit
    x = 0
    parts = []
    for cells, w, h in parsed.values():
        for rx, ry, rw, rh in to_rects(cells):
            parts.append(
                f'<rect x="{x + rx * unit}" y="{ry * unit}" width="{rw * unit}" height="{rh * unit}"/>'
            )
        x += (w + pitch) * unit
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<!-- {HEADER.split(" — ")[0]} -->\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total_w} {total_h}" '
        'fill="currentColor" role="img" aria-label="Memory letter samples">\n'
        f"  {''.join(parts)}\n"
        "</svg>\n"
    )



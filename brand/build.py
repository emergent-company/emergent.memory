        " */",
        f':root,\n[data-theme="{name}"] {{',
        f"  color-scheme: {mode};",
        "",
        f"  --color-base-100: {c['surface.base'].css};        /* surface */",
        f"  --color-base-200: {c['surface.page'].css};        /* page background */",

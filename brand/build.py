# ── colour ────────────────────────────────────────────────────────────────


def oklch_to_linear(lightness: float, chroma: float, hue: float) -> tuple[float, float, float]:
    """OKLCH → linear sRGB (Björn Ottosson's matrices)."""
    h = math.radians(hue)
    a = chroma * math.cos(h)
    b = chroma * math.sin(h)

    l_ = lightness + 0.3963377774 * a + 0.2158037573 * b
    m_ = lightness - 0.1055613458 * a - 0.0638541728 * b
    s_ = lightness - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_**3, m_**3, s_**3

    r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    return (min(max(r, 0.0), 1.0), min(max(g, 0.0), 1.0), min(max(bl, 0.0), 1.0))


def linear_to_srgb(c: float) -> float:
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def luminance(linear: tuple[float, float, float]) -> float:
    r, g, b = linear
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: tuple[float, float, float], b: tuple[float, float, float]) -> float:
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def clamp8(x: float) -> int:
    return min(255, max(0, round(x * 255)))


class Color:
    """A resolved token colour, rendering itself in every form consumers need."""

    def __init__(self, lightness: float, chroma: float, hue: float, alpha: float = 1.0):
        self.oklch = (lightness, chroma, hue)
        self.alpha = alpha
        self.linear = oklch_to_linear(lightness, chroma, hue)
        rgb = [clamp8(linear_to_srgb(c)) for c in self.linear]
        self.rgb255 = tuple(rgb)
        self.hex = "#" + "".join(f"{c:02x}" for c in rgb)
        self.css = f"oklch({lightness} {chroma} {hue}" + (f" / {alpha})" if alpha != 1 else ")")
        self.srgb = tuple(linear_to_srgb(c) for c in self.linear)

    def __repr__(self) -> str:
        return f"Color({self.hex})"


# ── token loading and validation ──────────────────────────────────────────

RESERVED = ("$value", "$type", "$description", "$extensions", "$deprecated", "$root")


class TokenError(SystemExit):
    pass


def is_token(node: dict) -> bool:
    return isinstance(node, dict) and "$value" in node


def flatten(node, path="", inherited_type=None, out=None):
    """Walk the DTCG group/token tree into {path: (token, type)}."""
    out = {} if out is None else out
    if not isinstance(node, dict):
        raise TokenError(f"{path or '<root>'}: group must be an object")
    group_type = node.get("$type", inherited_type)
    for key, child in node.items():
        if key.startswith("$"):
            continue
        if "." in key or "{" in key or "}" in key:
            raise TokenError(f"{path}.{key}: token and group names must not contain '.', '{{' or '}}'")
        child_path = f"{path}.{key}" if path else key
        if is_token(child):
            t = child.get("$type", group_type)
            if t is None:
                raise TokenError(f"{child_path}: no $type on the token or any parent group")
            out[child_path] = (child, t)
        else:
            flatten(child, child_path, group_type, out)
    return out


def load():
    if not TOKENS_PATH.exists():
        raise TokenError(f"missing {TOKENS_PATH}")
    doc = json.loads(TOKENS_PATH.read_text())
    flat = flatten(doc)
    resolved = {}
    for path, (token, type_) in flat.items():
        resolved[path] = (token, type_)

    def resolve_path(path: str) -> Color:
        token, type_ = resolved[path]
        value = token["$value"]
        seen = [path]
        while isinstance(value, str) and value.startswith("{") and value.endswith("}"):
            target = value[1:-1]
            if target not in resolved:
                raise TokenError(f"{path}: alias {value} does not exist")
            if target in seen:
                raise TokenError(f"{path}: circular alias {' -> '.join(seen + [target])}")
            seen.append(target)
            value = resolved[target][0]["$value"]
        if type_ != "color":
            raise TokenError(f"{path}: expected color, got {type_}")
        if not isinstance(value, dict) or "components" not in value:
            raise TokenError(f"{path}: colour must be {{colorSpace, components}}")
        space = value.get("colorSpace")
        if space != "oklch":
            raise TokenError(f"{path}: only oklch is allowed as a source colour space (got {space})")
        c = value["components"]
        return Color(*c, alpha=value.get("alpha", 1))

    colors = {p: resolve_path(p) for p, (_, t) in resolved.items() if t == "color"}
    others = {p: resolved[p][0]["$value"] for p, (_, t) in resolved.items() if t != "color"}
    types = {p: t for p, (_, t) in resolved.items()}
    return doc, colors, others, types



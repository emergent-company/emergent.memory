# ── the mark: brass tile, drawn M ─────────────────────────────────────────
#
# The letter is a path, not live text. The shipped monogram set it in the system
# font, so the letterform changed with the font stack and per platform, could
# not be exported as an outline, and could not be used where no CSS exists (an
# email, an app icon, a favicon). This is the letter, drawn once in its own 24u
# frame; the plate is a 64u rounded square. main() re-derives every number below
# from the token file, so the drawing cannot drift from the contract.

GLYPH_FRAME = 24
GLYPH_APEX_INNER = 14.0  # where the V's crotch starts, in glyph units
GLYPH_APEX_OUTER = 23.0  # where the V's tip reaches; 1u short of the baseline


def mark_geometry() -> tuple[float, float, float, float, float]:
    """(side, radius, glyphCap, glyphStroke, pad) from the tokens."""
    side = float(SEM["logo.mark.side"])
    radius = float(SEM["logo.mark.radius"])
    cap = float(SEM["logo.mark.glyphCap"])
    stroke = float(SEM["logo.mark.glyphStroke"])
    return side, radius, cap, stroke, (side - cap) / 2


def glyph_path() -> str:
    """The M as one closed outline: two stems and a constant-thickness V band.

    Twelve points, no curves. The V's top and bottom edges have the same slope,
    so the band keeps its vertical thickness and the letter reads as a letter
    at 16px instead of thinning into a wedge.
    """
    s = float(SEM["logo.mark.glyphStroke"])
    f = GLYPH_FRAME
    yi, yo = GLYPH_APEX_INNER, GLYPH_APEX_OUTER
    pts = [
        (0, f), (0, 0), (s, 0), (f / 2, yi), (f - s, 0), (f, 0),
        (f, f), (f - s, f), (f - s, yo - yi), (f / 2, yo), (s, yo - yi), (s, f),
    ]
    return "M" + " L".join(f"{x:g},{y:g}" for x, y in pts) + " Z"


def gradient_line(side: float, angle: float) -> tuple[float, float, float, float]:
    """CSS `linear-gradient(<angle>deg)` as SVG gradient endpoints.

    The line passes through the centre and its half-length is
    (|sin a| + |cos a|) * side / 2 — that is the CSS gradient-line length, not
    half the side. Using half the side makes the SVG reach its end colours at the
    corner and look more saturated than the same angle written as CSS, which is
    the one thing a brand file must not do: `memory-tile.svg` and a
    `linear-gradient()` of the same token angle have to render identically.
    """
    a = math.radians(angle)
    dx, dy = math.sin(a), -math.cos(a)
    cx = cy = side / 2
    half = (abs(dx) + abs(dy)) * side / 2
    return (cx - dx * half, cy - dy * half, cx + dx * half, cy + dy * half)


def mark_problems() -> list[str]:
    """The tile's contract, asserted — the same ranges the catalogue mirrors."""
    problems = []
    side, radius, cap, stroke, pad = mark_geometry()
    ratio_r = radius / side
    ratio_c = cap / side
    if not 0.20 <= ratio_r <= 0.24:
        problems.append(f"mark: radius/side = {ratio_r:.3f}, outside 0.20-0.24 (squircle, not a circle)")
    if not 0.36 <= ratio_c <= 0.44:
        problems.append(f"mark: glyphCap/side = {ratio_c:.3f}, outside 0.36-0.44 (too small to read, or crowding the plate)")
    if cap * 16 / side < 6:
        problems.append(f"mark: the glyph is {cap * 16 / side:.1f}px at a 16px tile — under 6px it mushes")
    if pad <= 0:
        problems.append("mark: glyphCap must be smaller than side")
    ink = COLOR["logo.mark.glyphInk"]
    for name in ("gradientFrom", "gradientTo"):
        r = contrast(ink.linear, COLOR[f"logo.mark.{name}"].linear)
        if r < 4.5:
            problems.append(f"mark: glyph ink on logo.mark.{name} = {r:.2f} < 4.5 (AA text)")
    r = contrast(COLOR["logo.mark.glyphOnInk"].linear, COLOR["logo.mark.plateInk"].linear)
    if r < 4.5:
        problems.append(f"mark: reverse glyph on plate = {r:.2f} < 4.5 (AA text)")
    coords = [tuple(map(float, p.split(","))) for p in glyph_path()[1:-2].split(" L")]
    if len(coords) != 12:
        problems.append(f"mark: glyph outline has {len(coords)} points, expected 12")
    if any(not (0 <= x <= GLYPH_FRAME and 0 <= y <= GLYPH_FRAME) for x, y in coords):
        problems.append("mark: a glyph coordinate falls outside the 24u frame")
    if stroke <= 0 or stroke * 2 >= GLYPH_FRAME:
        problems.append("mark: glyphStroke leaves no counter space")
    return problems



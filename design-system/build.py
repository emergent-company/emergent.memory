def swift() -> str:
    c = roles("dark")
    light = roles("light")
    out = [
        "// " + HEADER,
        "//",
        "// Resolved sRGB values (OKLCH is converted at build time so the platform",
        "// never needs a colour-space shim). Import SwiftUI or UIKit as needed.",
        "",
        "import SwiftUI",
        "",
        "public enum MemoryBrand {",
        "    public enum Palette {",
    ]
    for mode, colors in (("dark", c), ("light", light)):
        out.append(f"        // MARK: {mode}")
        for key in [
            "surface.page", "surface.base", "surface.raised", "surface.deep",
            "content.body", "content.strong",
            "interactive.primary", "interactive.onPrimary",
            "interactive.secondary", "interactive.onSecondary",
            "interactive.accent", "interactive.onAccent",
            "status.info", "status.success", "status.warning", "status.error",
            "border.line", "border.strong", "focus.ring",
        ]:
            col: Color = colors[key]
            name = mode + "".join(p.capitalize() for p in key.replace(".", " ").split())
            r, g, b = col.srgb
            out.append(
                f"        public static let {name} = SwiftUI.Color(.sRGB, red: {r:.4f}, green: {g:.4f}, blue: {b:.4f}, opacity: 1)"
            )
    out += ["", "        public static let dataSeries: [SwiftUI.Color] = ["]
    for i in range(1, 9):
        col = COLOR[f"color.data.{i}"]
        r, g, b = col.srgb
        out.append(f"            SwiftUI.Color(.sRGB, red: {r:.4f}, green: {g:.4f}, blue: {b:.4f}, opacity: 1),")
    out += ["        ]", "    }", ""]

    # Type: sizes are rem-based tokens; 1rem = 16pt at the platform default.
    sizes = {k.split("type.size.")[1]: float(SEM[k]["value"]) * 16 for k in SEM if k.startswith("type.size.")}
    out += [
        "    /// Text styles. The UI uses the system stack by decision: no web font,",
        "    /// no bundled typeface. Sizes derive from the token scale (1rem = 16pt).",
        "    public enum Text {",
    ]
    for name, pt in sorted(sizes.items(), key=lambda kv: kv[1]):
        # A Swift identifier cannot begin with a digit, and the scale has 2xl/3xl
        # and friends, so every member takes a `size` prefix.
        ident = "size" + "".join(p[:1].upper() + p[1:] for p in name.split("-"))
        out.append(f"        public static let {ident} = Font.system(size: {pt:g}, weight: .regular)")
    out += ["    }", ""]

    out += ["    /// Corner radii from the semantic levers."]
    out += ["    public enum Radius {"]
    for name in ("selector", "field", "box"):
        pt = float(SEM[f"radius.{name}"]["value"]) * 16
        out.append(f"        public static let {name}: CGFloat = {pt:g}")
    out += ["    }", ""]


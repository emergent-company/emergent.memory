def main(argv: list[str]) -> int:
    check = "--check" in argv

    global COLOR, SEM, TYPES, SEM_FAMILIES
    _, COLOR, SEM, TYPES = load()
    # Both modes must declare the same roles: a role present in one mode only is
    # a surface that silently renders nothing in the other, and the flat JSON
    # emitter would die on a raw KeyError instead of naming the omission.
    mode_gap = sorted(set(roles("dark")) ^ set(roles("light")))
    if mode_gap:
        raise TokenError(
            "semantic.dark and semantic.light must declare the same roles; "
            "only one mode has: " + ", ".join(mode_gap)
        )
    SEM_FAMILIES = {
        "body": SEM["type.fontFamily.body"],
        "heading": SEM["type.fontFamily.heading"],
        "mono": SEM["type.fontFamily.mono"],
    }

    files, failures = outputs()

    problems: list[str] = []
    if failures:
        problems += failures
    problems += mark_problems()

    if check:
        for path, content in files.items():
            if not path.exists():
                problems.append(f"missing generated file: {path.relative_to(ROOT.parent)}")
            elif path.read_text() != content:
                problems.append(f"stale generated file: {path.relative_to(ROOT.parent)} (run `task brand:build`)")
        for p in sorted(problems):
            print(f"FAIL {p}", file=sys.stderr)
        if problems:
            return 1
        print(f"brand: {len(files)} generated files match, {len(COLOR)} colours, contrast OK")
        return 0

    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    for p in problems:
        print(f"WARN {p}", file=sys.stderr)
    print(f"brand: wrote {len(files)} files, resolved {len(COLOR)} colours")
    return 1 if failures else 0



def _ramp(ramp: str) -> str:
    pref = f"color.{ramp}."
    steps = sorted(
        ((int(k[len(pref):]), v) for k, v in COLOR.items() if k.startswith(pref)),
        key=lambda kv: kv[0],
    )
    out = [f'<div class="ramp"><div class="name">{ramp}</div>']
    for step, col in steps:
        ink = "#0b0b0c" if luminance(col.linear) > 0.35 else "#f8f8f9"
        out.append(
            f'<div class="sw" style="background:{col.css};color:{ink}" data-copy="{col.css}" '
            f'title="{ramp}.{step} — {col.hex} {col.css}"><span>{step}</span></div>'
        )
    out.append("</div>")
    return "".join(out)



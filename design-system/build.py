def _contrast_table() -> str:
    out = [
        '<table><thead><tr><th>Pair</th><th style="text-align:right">Ratio</th>'
        '<th style="text-align:right">Min</th><th>WCAG 2.2</th></tr></thead><tbody>'
    ]
    for mode in ("dark", "light"):
        out.append(
            f'<tr><td colspan="4" style="padding-top:1rem"><b>{mode}</b></td></tr>'
        )
        for fg, bg, minimum, why in CONTRAST_PAIRS:
            f = COLOR[fg.replace("{mode}", mode)]
            b = COLOR[bg.replace("{mode}", mode)]
            ratio = contrast(f.linear, b.linear)
            ok = ratio >= minimum
            pair = f"{fg.replace('semantic.{mode}.', '')} on {bg.replace('semantic.{mode}.', '')}"
            out.append(
                f'<tr><td><span class="mono">{pair}</span>'
                f'<br><span style="font-size:.6875rem;opacity:.5">{why}</span></td>'
                f'<td class="num">{ratio:.2f}</td><td class="num">{minimum:g}</td>'
                f'<td class="{"pass" if ok else "fail"}">{"pass" if ok else "FAIL"}</td></tr>'
            )
    out.append("</tbody></table>")
    return "".join(out)



def flat_json() -> str:
    """Every token, colour or not, with its resolved value.

    A consumer that reads this file should not have to fall back to the DTCG
    source to find a spacing step or a duration — that would defeat the point of
    publishing a resolved form. Non-colour tokens carry `css` (the value as a CSS
    string) and no hex.
    """
    tokens = {}
    for path in sorted(set(COLOR) | set(SEM)):
        entry: dict[str, object] = {"type": TYPES[path]}
        if path in COLOR:
            entry["hex"] = COLOR[path].hex
            entry["srgb"] = [round(v, 6) for v in COLOR[path].srgb]
            entry["css"] = COLOR[path].css
            entry["light_hex"] = (
                COLOR["semantic.light." + path[len("semantic.dark."):]].hex
                if path.startswith("semantic.dark.") else None
            )
        else:
            entry["css"] = css_dimension(SEM[path])
            # The raw DTCG `$value` (a {value, unit} object, a list, a number)
            # for tokens that are not colours — that is where it is not already
            # expressed by `css`. Colour aliases resolve through `hex`/`css`,
            # so they carry no `value` rather than a misleading null.
            entry["value"] = SEM[path]
        tokens[path] = entry
    return json.dumps({"$description": HEADER, "tokens": tokens}, indent=2, sort_keys=True) + "\n"



def go() -> str:
    c = roles("dark")
    light = roles("light")

    def ident(key: str, prefix: str = "") -> str:
        """`interactive.onPrimary` → `InteractiveOnPrimary`. gofmt does not care
        about the case, but a Go consumer does."""
        return prefix + "".join(p[:1].upper() + p[1:] for p in key.split("."))

    def const_group(comment: str, entries: list[tuple[str, str]]) -> list[str]:
        """Emit one alignment group.

        gofmt aligns `=` across consecutive lines, so the generator has to emit
        the alignment itself: brand.go is a tracked .go file and
        scripts/preflight/gofmt-tracked.sh fails the build on any file gofmt
        would rewrite.
        """
        out = []
        if comment:
            out.append(f"\t// {comment}")
        width = max(len(name) for name, _ in entries)
        out += [f"\t{name.ljust(width)} = {value}" for name, value in entries]
        return out

    dark_keys = [
        "surface.page", "surface.base", "surface.raised", "surface.deep",
        "content.body", "content.strong",
        "interactive.primary", "interactive.onPrimary",
        "interactive.secondary", "interactive.onSecondary",
        "interactive.accent", "interactive.onAccent",
        "status.info", "status.success", "status.warning", "status.error",
        "border.line", "border.strong", "focus.ring",
    ]
    light_keys = ["surface.base", "content.body", "interactive.primary", "status.error"]

    lines = [
        "// " + HEADER,
        "//",
        "// Hex values are resolved from OKLCH at build time. The CLI/TUI uses them",
        "// directly (lipgloss accepts #rrggbb) and must fall back to no colour when",
        "// NO_COLOR is set or the terminal is not a TTY.",
        "",
        "package brand",
        "",
    ]
    body = []
    body += const_group("", [(ident(k), f'"{c[k].hex}"') for k in dark_keys])
    body += [""]
    body += const_group(
        "Light-mode equivalents, for surfaces that opt in.",
        [(ident(k, "Light"), f'"{light[k].hex}"') for k in light_keys],
    )
    lines += ["const (", *body, ")", ""]

    lines += ["// DataSeries is the categorical chart palette, in assignment order.", "var DataSeries = []string{"]
    lines += [f'\t"{COLOR[f"color.data.{i}"].hex}",' for i in range(1, 9)]
    lines += ["}", ""]

    ref_keys = [
        p for p in sorted(COLOR)
        if p.startswith("color.") and not p.startswith("color.data.")
    ]
    width = max(len(f'"{p}"') for p in ref_keys) + 1
    lines += ["// Ref holds the reference ramps, for charts and one-off renderers that must pick a step.", "var Ref = map[string]string{"]
    lines += [f'\t{(chr(34) + p + chr(34) + ":").ljust(width)} "{COLOR[p].hex}",' for p in ref_keys]

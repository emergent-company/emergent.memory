def role_vars(mode: str, prefix: str) -> list[str]:
    c = roles(mode)
    out = []
    for name, key, note in ROLE_ORDER:
        suffix = f"  /* {note} */" if note else ""
        out.append(f"  --brand-{prefix}{name}: {c[key].css};{suffix}")
    return out


